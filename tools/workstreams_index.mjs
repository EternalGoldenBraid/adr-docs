#!/usr/bin/env node
// Regenerate workstreams/index.md from each file's front matter (status, title, summary).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";
import { fileURLToPath } from "node:url";

const directory = fileURLToPath(new URL("../workstreams/", import.meta.url));
const ORDER = ["in-progress", "accepted", "proposed", "blocked", "done", "declined"];
const rows = [];
for (const file of readdirSync(directory)) {
  if (!file.endsWith(".md") || ["index.md", "README.md"].includes(file)) continue;
  const front = /^---\n([\s\S]*?)\n---/.exec(readFileSync(join(directory, file), "utf8"))?.[1] ?? "";
  const field = name => new RegExp(`^${name}:\\s*(.*)$`, "m").exec(front)?.[1].trim() ?? "";
  rows.push({ file, status: field("status") || "proposed", title: field("title") || basename(file, ".md"), summary: field("summary") });
}
rows.sort((a, b) => ORDER.indexOf(a.status) - ORDER.indexOf(b.status) || a.file.localeCompare(b.file));
const out = ["---", "nav: Workstreams", "---", "", "# Workstreams", "",
  "Generated by `npm run workstreams`; see [README](./README) for the status values.", "",
  "| Status | Request | Summary |", "| --- | --- | --- |",
  ...rows.map(row => `| ${row.status} | [${row.title}](./${basename(row.file, ".md")}) | ${row.summary.replace(/\|/g, "\\|")} |`), ""];
writeFileSync(join(directory, "index.md"), out.join("\n"));

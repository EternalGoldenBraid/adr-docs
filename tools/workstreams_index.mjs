#!/usr/bin/env node
// Regenerate workstreams/index.md (grouped by status) from each file's front matter.
// `--json [dir]` prints the board as JSON instead.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { readBoard, STATUSES } from "../src/workstreams.mjs";

const args = process.argv.slice(2);
const directory = args.find(a => !a.startsWith("--")) ?? fileURLToPath(new URL("../workstreams/", import.meta.url));
const board = readBoard(directory);
if (args.includes("--json")) { console.log(JSON.stringify(board, null, 2)); process.exit(0); }

const cell = text => text.replace(/\|/g, "\\|");
const progress = i => i.steps.total ? `${i.steps.done}/${i.steps.total}` : "";
const out = ["---", "nav: Workstreams", "---", "", "# Workstreams", "",
  "Generated by `npm run workstreams` (JSON: `npm run workstreams -- --json`); schema in the [README](./README).", ""];
for (const status of [...STATUSES, ...new Set(board.items.map(i => i.status).filter(s => !STATUSES.includes(s)))]) {
  const rows = board.items.filter(i => i.status === status);
  if (!rows.length) continue;
  out.push(`## ${status} (${rows.length})`, "", "| Request | Owner | Steps | Depends on | Summary |", "| --- | --- | --- | --- | --- |",
    ...rows.map(i => `| [${cell(i.title)}](./${i.id}) | ${cell(i.owner)} | ${progress(i)} | ${i.depends_on.map(d => `[${d}](./${d})`).join(", ")} | ${cell(i.summary)} |`), "");
}
writeFileSync(join(directory, "index.md"), out.join("\n"));
